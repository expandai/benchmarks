"""Composite answer-accuracy index across the five independent datasets, from the per-task records (offline).

The index is the equal-weight mean of five per-dataset accuracies, each on a 0-100 scale:

* WebCode RAG: ``correct`` (the answer is right), not ``grounded``; groundedness rises with evidence length,
  which is a property of the provider's excerpts rather than of answer quality. ``--webcode-grounded`` gives
  the variant with ``grounded`` for comparison.
* SimpleQA Verified: per-task accuracy (the headline F1 is not a per-task mean; with >= 99.5 % of questions
  attempted the two agree to within 0.2 points).
* FRAMES, Seal-Hard: per-task accuracy under the official graders.
* AA-Omniscience: accuracy (1 when the grade is CORRECT); the Omniscience Index is on a different scale.

Seal-0 is not an input: its 111 questions are a subset of Seal-Hard. Only systems with a complete run on all
five datasets are indexed. Terminal failures score 0 on the full denominator, as in every table.

Uncertainty: a stratified percentile bootstrap (10,000 resamples, seed 0) that resamples tasks within each
dataset independently and recomputes the index. Paired differences against Expand resample the same task
indices for both systems, so the interval reflects the per-task pairing, as in ``runs/paired.py``.

    "$EXA_BENCH_VENV/bin/python" runs/index.py [--webcode-grounded]

Writes ``runs/index.json`` (or ``runs/index-webcode-grounded.json``) and replaces the table between the
``index:begin`` / ``index:end`` markers in ``README.md`` (the default variant only).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from _records import BAKEOFF_ROOT, run_dirs  # noqa: E402
from paired import AA_RUN, aa_scores, harness_scores  # noqa: E402

EXPAND = "rag-expand"
RESAMPLES = 10_000
SEED = 0
README_BEGIN = "<!-- index:begin (generated by runs/index.py) -->"
README_END = "<!-- index:end -->"


def datasets(webcode_key: str) -> list[tuple[str, str, tuple[str, ...], str, int]]:
    # (name, suite, record roots, grade score key, suite size)
    return [
        ("WebCode", "webcode-rag", ("pilot-20", "webcode-rag"), webcode_key, 307),
        ("SimpleQA Verified", "simpleqa-verified-official", ("official/simpleqa-verified-official",), "score", 1000),
        ("FRAMES", "frames-official", ("official/frames-official",), "score", 824),
        ("Seal-Hard", "seal-hard-official", ("official/seal-hard-official",), "score", 254),
    ]


def per_task_scores(webcode_key: str) -> tuple[list[str], dict[str, list[np.ndarray]]]:
    """Dataset names, and system -> one aligned per-task score vector per dataset (complete systems only)."""
    names: list[str] = []
    by_system: dict[str, list[dict[str, float]]] = {}
    for name, suite, roots, key, size in datasets(webcode_key):
        names.append(name)
        for system, (run_dir, _root) in run_dirs([HERE / r for r in roots], suite).items():
            scores = harness_scores(run_dir, key, size)
            if scores is not None:
                by_system.setdefault(system, []).append(scores)
    names.append("AA-Omniscience")
    for system_dir in sorted(p for p in AA_RUN.iterdir() if p.is_dir()):
        scores = aa_scores(system_dir, 600)
        if scores is not None:
            by_system.setdefault("rag-" + system_dir.name, []).append(scores)
    complete = {s: v for s, v in by_system.items() if len(v) == len(names)}
    expand = complete[EXPAND]
    keys = [sorted(d) for d in expand]  # Expand's task ids fix the order every system is aligned to
    for system, vectors in complete.items():
        for name, expected, scores in zip(names, keys, vectors):
            if set(scores) != set(expected):
                raise ValueError(f"{name}: task ids for {system} do not match {EXPAND}")
    aligned = {s: [np.array([v[i][t] for t in keys[i]], dtype=float) for i in range(len(names))] for s, v in complete.items()}
    return names, aligned


def bootstrap(aligned: dict[str, list[np.ndarray]]) -> dict[str, Any]:
    rng = np.random.default_rng(SEED)
    sizes = [len(v) for v in aligned[EXPAND]]
    # One index matrix per dataset, shared by every system so paired differences pair the same tasks.
    draws = [rng.integers(0, n, size=(RESAMPLES, n)) for n in sizes]
    samples = {s: np.mean([v[i][draws[i]].mean(axis=1) for i in range(len(sizes))], axis=0) * 100 for s, v in aligned.items()}
    out: dict[str, Any] = {}
    for system, vectors in aligned.items():
        point = float(np.mean([v.mean() for v in vectors]) * 100)
        diff = samples[EXPAND] - samples[system]
        out[system] = {
            # Keep full precision until presentation: rounding here changes both displayed
            # tenths (e.g. 270/307 becomes 88.0 instead of 87.9) and near-zero CI decisions.
            "index": point,
            "low": float(np.percentile(samples[system], 2.5)),
            "high": float(np.percentile(samples[system], 97.5)),
            "per_dataset": [float(v.mean() * 100) for v in vectors],
            "expand_minus": None
            if system == EXPAND
            else {
                "diff": float(np.mean([a.mean() - b.mean() for a, b in zip(aligned[EXPAND], vectors)]) * 100),
                "low": float(np.percentile(diff, 2.5)),
                "high": float(np.percentile(diff, 97.5)),
            },
        }
    return out


def markdown(names: list[str], result: dict[str, Any]) -> str:
    head = "| System | Index [95% CI] | " + " | ".join(names) + " | Expand minus system [95% CI] |"
    rule = "|---|---:|" + "---:|" * len(names) + "---|"
    lines = [head, rule]
    for system, row in sorted(result.items(), key=lambda kv: -kv[1]["index"]):
        cells = " | ".join(f"{x:.1f}" for x in row["per_dataset"])
        d = row["expand_minus"]
        paired = "—" if d is None else f"{d['diff']:+.1f} [{d['low']:+.1f}, {d['high']:+.1f}]{' *' if d['low'] > 0 or d['high'] < 0 else ''}"
        lines.append(f"| {system.removeprefix('rag-')} | {row['index']:.1f} [{row['low']:.1f}–{row['high']:.1f}] | {cells} | {paired.replace('-', '−')} |")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--webcode-grounded", action="store_true", help="use WebCode grounded instead of correct")
    args = parser.parse_args()
    key = "grounded" if args.webcode_grounded else "score"
    names, aligned = per_task_scores(key)
    result = bootstrap(aligned)
    payload = {"datasets": names, "webcode_metric": "grounded" if args.webcode_grounded else "correct",
               "resamples": RESAMPLES, "seed": SEED, "systems": result}
    out = HERE / ("index-webcode-grounded.json" if args.webcode_grounded else "index.json")
    out.write_text(json.dumps(payload, indent=2) + "\n")
    table = markdown(names, result)
    print(table)
    if not args.webcode_grounded:
        readme = BAKEOFF_ROOT / "README.md"
        text = readme.read_text()
        if README_BEGIN in text and README_END in text:
            start = text.index(README_BEGIN) + len(README_BEGIN)
            text = text[:start] + "\n" + table + "\n" + text[text.index(README_END):]
            readme.write_text(text)


if __name__ == "__main__":
    main()
