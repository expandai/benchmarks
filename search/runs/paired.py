"""Paired differences, Expand minus each competitor, per suite, from the stored per-task grades (offline).

For every suite and every competitor whose run is complete, the per-task scores of Expand and the
competitor are paired task by task, and the mean paired difference gets a 95 % paired
percentile bootstrap interval (upstream ``bootstrap_mean`` over the per-task differences: 10,000
resamples, seed 0). Per-task scores:

* WebCode RAG: ``grounded`` and ``score`` (correct) from ``grade.json``, as ``runs/report.py`` reads them.
* SimpleQA Verified, SealQA, FRAMES (official graders): ``score`` from ``grade.json``, the per-task
  accuracy ``runs/official/report.py`` averages (SimpleQA Verified's headline F1 is not a per-task
  mean; with ≥ 99.5 % of questions attempted it equals accuracy to within 0.2 points).
* AA-Omniscience: 1 when ``grade == "CORRECT"``, else 0.

Terminal failures (a harness task that ended in ``error.json`` after every pass; an AA question that
ended in an execution error) score 0, as in the headline tables, so every pair covers the full suite.

A run counts as complete when every task of the suite has a terminal record (``grade.json`` or
``error.json``; AA: ``status`` complete or error). Incomplete runs (partial rows, runs in flight)
are skipped and listed. ``--exclude SUITE:SYSTEM`` skips a pair explicitly (``*:SYSTEM`` skips a system everywhere).

    "$EXA_BENCH_VENV/bin/python" runs/paired.py [--exclude SUITE:SYSTEM ...]

Writes ``runs/paired.json`` and replaces the table between the ``paired:begin`` / ``paired:end``
markers in ``README.md``.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
from _records import BAKEOFF_ROOT, SYSTEM_ORDER, bootstrap_mean, read, run_dirs, task_dirs  # noqa: E402

EXPAND = "rag-expand"
BASELINE = "rag-model-only"
AA_RUN = BAKEOFF_ROOT / "aa-stirrup" / "runs" / "full-600"
# (column key, title, suite, record roots, grade score key, suite size)
HARNESS_COLUMNS = (
    ("webcode-grounded", "WebCode grounded", "webcode-rag", ("pilot-20", "webcode-rag"), "grounded", 307),
    ("webcode-correct", "WebCode correct", "webcode-rag", ("pilot-20", "webcode-rag"), "score", 307),
    ("simpleqa-verified", "SimpleQA Verified acc.", "simpleqa-verified-official", ("official/simpleqa-verified-official",), "score", 1000),
    ("seal-0", "Seal-0", "seal-0-official", ("official/seal-0-official",), "score", 111),
    ("seal-hard", "Seal-Hard", "seal-hard-official", ("official/seal-hard-official",), "score", 254),
    ("frames", "FRAMES", "frames-official", ("official/frames-official",), "score", 824),
)
AA_COLUMN = ("aa-omniscience", "AA-Omniscience acc.", "aa-omniscience-public", 600)
README_BEGIN = "<!-- paired:begin (generated by runs/paired.py) -->"
README_END = "<!-- paired:end -->"


def harness_scores(run_dir: Path, key: str, suite_tasks: int) -> dict[str, float] | None:
    """task id -> score, or None while the run is incomplete."""
    tasks = task_dirs(run_dir)
    terminal = [p for p in tasks if (p / "grade.json").exists() or (p / "error.json").exists()]
    if len(tasks) != suite_tasks or len(terminal) != suite_tasks:
        return None
    scores: dict[str, float] = {}
    for task in tasks:
        grade_path = task / "grade.json"
        if not grade_path.exists():
            scores[task.name] = 0.0  # terminal failures count as zero
            continue
        grade = read(grade_path)  # Invalid completed records must fail, not shrink a paired cohort.
        if grade["task_id"] != task.name:
            raise ValueError(f"{grade_path}: grade task_id does not match its directory")
        value = float(grade["scores"][key])
        if not math.isfinite(value) or not 0 <= value <= 1:
            raise ValueError(f"{grade_path}: invalid {key} score {value}")
        scores[task.name] = value
    return scores


def aa_scores(system_dir: Path, expected: int) -> dict[str, float] | None:
    paths = sorted(system_dir.glob("aao-*.json"))
    if len(paths) != expected:
        return None
    records = [read(path) for path in paths]
    if any(r.get("status") not in ("complete", "error") for r in records):
        return None
    for path, record in zip(paths, records):
        if record["id"] != path.stem:
            raise ValueError(f"{path}: record id does not match its filename")
        if record["status"] == "complete" and record.get("grade") not in (
            "CORRECT", "INCORRECT", "PARTIAL_ANSWER", "NOT_ATTEMPTED"
        ):
            raise ValueError(f"{path}: complete record has an invalid grade")
    # An execution error counts as not attempted (0), like the headline tables.
    return {r["id"]: float(r.get("status") == "complete" and r.get("grade") == "CORRECT") for r in records}


def paired(expand: dict[str, float], other: dict[str, float]) -> dict[str, Any]:
    if not expand or set(expand) != set(other):
        raise ValueError("Paired scores must cover the same non-empty set of task ids")
    common = sorted(expand)
    diffs = [expand[t] - other[t] for t in common]
    interval = bootstrap_mean(diffs)
    return {
        "n": len(common),
        "expand_mean": sum(expand[t] for t in common) / len(common) if common else None,
        "competitor_mean": sum(other[t] for t in common) / len(common) if common else None,
        "diff": interval.estimate,
        "low": interval.low,
        "high": interval.high,
        "expand_better": sum(1 for d in diffs if d > 0),
        "competitor_better": sum(1 for d in diffs if d < 0),
    }


def collect(excluded: set[tuple[str, str]]) -> tuple[list[dict[str, Any]], list[str]]:
    rows: list[dict[str, Any]] = []
    skipped: list[str] = []
    for column, title, suite, roots, key, size in HARNESS_COLUMNS:
        found = run_dirs([HERE / r for r in roots], suite)
        if EXPAND not in found:
            skipped.append(f"{suite}: no {EXPAND} run")
            continue
        expand = harness_scores(found[EXPAND][0], key, size)
        if expand is None:
            skipped.append(f"{suite}:{EXPAND} (incomplete)")
            continue
        for system, (run_dir, _root) in found.items():
            if system in (EXPAND, BASELINE):
                continue
            if (suite, system) in excluded:
                skipped.append(f"{suite}:{system} (excluded)")
                continue
            other = harness_scores(run_dir, key, size)
            if other is None:
                skipped.append(f"{suite}:{system} (incomplete)")
                continue
            rows.append({"column": column, "title": title, "suite": suite, "system": system, **paired(expand, other)})
    column, title, suite, size = AA_COLUMN
    expand = aa_scores(AA_RUN / "expand", size) if (AA_RUN / "expand").is_dir() else None
    if expand is not None:
        for system_dir in sorted(p for p in AA_RUN.iterdir() if p.is_dir()):
            system = "rag-" + system_dir.name
            if system in (EXPAND, BASELINE):
                continue
            if (suite, system) in excluded or (suite, system_dir.name) in excluded:
                skipped.append(f"{suite}:{system_dir.name} (excluded)")
                continue
            other = aa_scores(system_dir, size)
            if other is None:
                skipped.append(f"{suite}:{system_dir.name} (incomplete)")
                continue
            rows.append({"column": column, "title": title, "suite": suite, "system": system, **paired(expand, other)})
    else:
        skipped.append(f"{suite}:expand (missing or incomplete)")
    return rows, skipped


def points(value: float | None) -> str:
    if value is None:
        return "—"
    text = f"{value * 100:+.1f}"
    return text.replace("-", "−")


def markdown(rows: list[dict[str, Any]]) -> str:
    columns = [(c[0], c[1]) for c in HARNESS_COLUMNS] + [(AA_COLUMN[0], AA_COLUMN[1])]
    columns = [c for c in columns if any(r["column"] == c[0] for r in rows)]
    order = {name: i for i, name in enumerate(SYSTEM_ORDER)}
    systems = sorted({r["system"] for r in rows}, key=lambda s: (order.get(s, 99), s))
    cell = {(r["system"], r["column"]): r for r in rows}
    lines = [
        "| Expand minus | " + " | ".join(title for _key, title in columns) + " |",
        "|---|" + "---:|" * len(columns),
    ]
    for system in systems:
        parts = []
        for key, _title in columns:
            r = cell.get((system, key))
            if r is None:
                parts.append("—")
                continue
            interval = f" [{points(r['low'])}, {points(r['high'])}]" if r["low"] is not None else ""
            mark = "" if r["low"] is None or r["low"] <= 0 <= r["high"] else " *"
            parts.append(f"{points(r['diff'])}{interval}{mark}")
        lines.append(f"| {system.removeprefix('rag-')} | " + " | ".join(parts) + " |")
    return "\n".join(lines)


def update_readme(table: str) -> bool:
    readme = BAKEOFF_ROOT / "README.md"
    text = readme.read_text()
    if README_BEGIN not in text or README_END not in text:
        return False
    head, rest = text.split(README_BEGIN, 1)
    _old, tail = rest.split(README_END, 1)
    readme.write_text(f"{head}{README_BEGIN}\n{table}\n{README_END}{tail}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--exclude", nargs="*", default=[], metavar="SUITE:SYSTEM")
    args = parser.parse_args()
    excluded: set[tuple[str, str]] = set()
    suites = [c[2] for c in HARNESS_COLUMNS] + [AA_COLUMN[2]]
    for item in args.exclude:
        suite, system = item.split(":", 1)
        excluded |= {(s, system) for s in suites} if suite == "*" else {(suite, system)}
    rows, skipped = collect(excluded)
    table = markdown(rows)
    out = {
        "method": "mean paired difference (Expand minus competitor) of per-task scores, terminal failures as 0; "
        "95% paired percentile bootstrap, 10,000 resamples, seed 0 (harness.statistics.bootstrap_mean)",
        "rows": rows,
        "skipped": skipped,
    }
    (HERE / "paired.json").write_text(json.dumps(out, indent=2) + "\n")
    print(table)
    if skipped:
        print("\nskipped: " + "; ".join(skipped))
    print("README.md updated" if update_readme(table) else "README.md has no paired markers; not updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
